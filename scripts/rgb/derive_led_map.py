#!/usr/bin/env python3
"""Derive the key -> LED table for the Crush 80 backlight and write zmk/src/rgb/led_map_data.h.

Source of the LED order: Ritwick Verma's Crush80_ZMK fork (Apache-2.0), zmk/src/rainy_rgb/led_map.c,
which read the stock firmware's switch-to-LED table. Its positions are indexed through ITS matrix
transform (88 keys, includes RC(4,12) and RC(5,12)); ours has 86 keys. So the table is re-keyed by
matrix (row, column), which does not depend on either transform.

Usage: derive_led_map.py <upstream-checkout> [<our dts>] [<out header>]
Reads files only; runs nothing from the upstream tree.
"""
import re, sys, os

def transform(path):
    t = open(path).read()
    m = re.search(r"map\s*=\s*<(.*?)>;", t, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [(int(r), int(c)) for r, c in re.findall(r"RC\((\d+),\s*(\d+)\)", body)]

def upstream_tables(path):
    t = open(path).read()
    a = re.search(r"pos_to_led\[[^\]]*\]\s*=\s*\{(.*?)\};", t, re.S).group(1)
    pos_to_led = [int(x) for x in re.findall(r"\d+", a)]
    b = re.search(r"extra_leds\[\]\[2\]\s*=\s*\{(.*?)\};", t, re.S).group(1)
    extras = [(int(p), int(l)) for p, l in re.findall(r"\{(\d+),\s*(\d+)\}", b)]
    return pos_to_led, extras

def main():
    up = sys.argv[1]
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    ours_dts = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "zmk/boards/crush80/crush80.dts")
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(here, "zmk/src/rgb/led_map_data.h")
    up_tf = transform(os.path.join(up, "zmk/boards/crush80/crush80.dts"))
    pos_to_led, extras = upstream_tables(os.path.join(up, "zmk/src/rainy_rgb/led_map.c"))
    assert len(up_tf) == len(pos_to_led), (len(up_tf), len(pos_to_led))
    rc_led = {rc: pos_to_led[i] for i, rc in enumerate(up_tf)}
    rc_extra = {}
    for pos, led in extras:
        rc_extra.setdefault(up_tf[pos], []).append(led)
    our_tf = transform(ours_dts)
    missing = [rc for rc in our_tf if rc not in rc_led]
    assert not missing, f"our keys without an LED: {missing}"
    used = [rc_led[rc] for rc in our_tf] + [l for rc in our_tf for l in rc_extra.get(rc, [])]
    assert len(used) == len(set(used)), "an LED is used twice"
    unused_key_leds = sorted(set(range(92)) - set(used))
    lines = ["/* GENERATED by scripts/rgb/derive_led_map.py. Do not edit.",
             " * LED order from the stock firmware's switch-to-LED table, via Ritwick Verma's Crush80_ZMK",
             " * (Apache-2.0, see zmk/src/rgb/NOTICE), re-keyed by matrix row/column for this board's 86-key transform.",
             f" * Key LEDs with no key on this board (not lit): {unused_key_leds} */",
             "#pragma once", "#include <stdint.h>", "",
             "#define C80_LED_NONE 0xFF", "#define C80_KEY_LEDS 92", "#define C80_TOTAL_LEDS 154", "",
             "/* matrix (row, column) -> first LED of that key, or C80_LED_NONE */",
             "static const uint8_t c80_rc_to_led[6][16] = {"]
    for r in range(6):
        row = [str(rc_led[(r, c)]) if (r, c) in rc_led and (r, c) in our_tf else "C80_LED_NONE" for c in range(16)]
        lines.append("    { " + ", ".join(row) + " },")
    lines += ["};", "", "/* keys lit by more than one LED: (row, column, extra LED) */",
              "static const uint8_t c80_extra_leds[][3] = {"]
    for rc in our_tf:
        for l in rc_extra.get(rc, []):
            lines.append(f"    {{ {rc[0]}, {rc[1]}, {l} }},")
    lines += ["};", ""]
    open(out, "w").write("\n".join(lines))
    print(f"wrote {out}: {len(our_tf)} keys, extras {[(rc,l) for rc in our_tf for l in rc_extra.get(rc,[])]}, unused key LEDs {unused_key_leds}")

main()
